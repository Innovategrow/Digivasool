// Builds a printable borrower agreement and opens the browser's print dialog,
// where "Save as PDF" downloads it. Done this way (rather than a PDF library)
// so names in Tamil, Hindi, etc. render correctly using the system fonts.
const esc = (v) => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const inr = (v) => '₹' + Number(v || 0).toLocaleString('en-IN');
const fmtDate = (v) => { const d = new Date(v); return isNaN(d) ? (v || '-') : d.toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' }); };

export function downloadBorrowerPdf(loan, t) {
  const interest = Math.max(0, (loan.monthly_interest_amount || 0) - (loan.field_visit_charge || 0) - (loan.document_fee || 0) - (loan.processing_fee || 0));
  const cash = Math.max(0, (loan.loan_amount || 0) - (loan.monthly_interest_amount || 0));
  const rows = (pairs) => pairs.filter(([, v]) => v !== '' && v != null)
    .map(([k, v]) => `<tr><th>${esc(k)}</th><td>${esc(v)}</td></tr>`).join('');
  const terms = ['terms1', 'terms2', 'terms3', 'terms4', 'terms5'].map(k => `<li>${esc(t(k))}</li>`).join('');

  const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Borrower Agreement - ${esc(loan.customer_name)}</title>
<style>
  @page{size:A4;margin:14mm}
  body{font-family:system-ui,-apple-system,'Segoe UI',sans-serif;color:#111;margin:0 auto;padding:20px;max-width:760px;font-size:15px}
  tr,li,.sigrow{break-inside:avoid}
  h1{font-size:20px;margin:0 0 2px} h2{font-size:14px;margin:22px 0 8px;border-bottom:1px solid #ccc;padding-bottom:4px;text-transform:uppercase;letter-spacing:.5px}
  .sub{color:#666;margin-bottom:12px} .top{display:flex;justify-content:space-between;align-items:flex-start;gap:16px}
  table{width:100%;border-collapse:collapse} th{text-align:left;width:38%;color:#555;font-weight:600;padding:4px 0;vertical-align:top} td{padding:4px 0}
  img.photo{width:90px;height:90px;object-fit:cover;border-radius:8px;border:1px solid #ccc} img.sig{max-width:260px;max-height:110px;border:1px solid #ccc;border-radius:6px}
  ol{padding-left:20px;line-height:1.6} .foot{margin-top:28px;color:#777;font-size:12px;text-align:center}
  .sigrow{display:flex;gap:32px;margin-top:18px;align-items:flex-end}
  .sigbox{flex:1;text-align:center} .sigarea{height:110px;display:flex;align-items:flex-end;justify-content:center;border-bottom:1.5px solid #111;padding-bottom:4px}
  .sigarea img{max-width:100%;max-height:104px} .siglabel{margin-top:6px;font-size:13px;font-weight:600}
  .siglabel small{display:block;font-weight:400;color:#666;font-size:11px}
</style></head><body>
<div class="top"><div><h1>DigiVasool — Loan Agreement</h1>
<div class="sub">Account No: <strong>${esc(loan.account_number)}</strong> · Generated ${esc(fmtDate(new Date()))}</div></div>
${loan.photo_url ? `<img class="photo" src="${esc(loan.photo_url)}" alt="">` : ''}</div>

<h2>Borrower details</h2><table>${rows([
    ['Name', loan.customer_name], ['Shop / business', loan.shop_name], ['Mobile', loan.customer_phone],
    ['Alternate mobile', loan.alternate_phone], ['Email', loan.customer_email], ['Area', loan.zone],
    ['Address', loan.customer_address], ['Aadhaar', loan.aadhaar_number],
  ])}</table>

<h2>Guarantor</h2><table>${rows([
    ['Name', loan.guarantor_name], ['Mobile', loan.guarantor_phone], ['Address', loan.guarantor_address],
  ]) || '<tr><td>Not provided</td></tr>'}</table>

<h2>Loan details</h2><table>${rows([
    ['Loan amount', inr(loan.loan_amount)],
    ['Charges (deducted upfront)', inr(loan.monthly_interest_amount)],
    ['  of which interest', inr(interest)], ['  of which field verification', inr(loan.field_visit_charge)],
    ['  of which document fee', inr(loan.document_fee)], ['  of which processing fee', inr(loan.processing_fee)],
    ['Cash handed over', inr(cash)], ['Total due', inr(loan.due_amount ?? loan.loan_amount)],
    ['Repayment', `${loan.repayment_frequency || 'monthly'}${loan.repayment_amount ? ' · ' + inr(loan.repayment_amount) : ''}`],
    ['Start date', fmtDate(loan.start_date)], ['Due date', fmtDate(loan.closing_date)],
  ])}</table>

<h2>Terms &amp; Conditions</h2><ol>${terms}</ol>
<p>${loan.terms_accepted ? `✔ Accepted by the borrower on ${esc(fmtDate(loan.terms_accepted_at))}.` : 'Not accepted.'}</p>

<h2>Signatures</h2>
<div class="sigrow">
  <div class="sigbox"><div class="sigarea">${loan.signature_url ? `<img src="${esc(loan.signature_url)}" alt="signature">` : ''}</div>
    <div class="siglabel">${esc(loan.customer_name)}<small>Borrower${loan.signature_url ? ' · digitally signed' : ' · signature not provided'}</small></div></div>
  <div class="sigbox"><div class="sigarea"></div><div class="siglabel">Authorised signatory<small>DigiVasool</small></div></div>
</div>
<div class="foot">This document was generated by DigiVasool.</div>
<script>window.onload=()=>setTimeout(()=>window.print(),300)</script>
</body></html>`;

  const w = window.open('', '_blank');
  if (!w) return false;
  w.document.open(); w.document.write(html); w.document.close();
  return true;
}
